# A print function is used to print something on the screen, where the text to be printed enclosed in quotation marks, either single (' ') or double (" "), is passed as an argument to the print function. It is a built-in function in Python that outputs the specified message to the console or terminal.

# Example of using the print function
print("Hello, World!")  # This will print the message "Hello, World!" to the console.

# We can also print multiple items by separating them with commas. The print function will automatically add a space between the items.
print("The answer is", 42)  # This will print "The answer is 42" to the console.

# We can also use the print function to print variables. For example:
name = "Alice"
print("Hello,", name)  # This will print "Hello, Alice" to the console.

